    A("- tau_mult 0.5 row non-decreasing in eta (and >= 0 at eta = 1): **%d of 12** grids." % n_mono)
    A("- e8 t0.5 above the eta = 0 cell at z >= %.2f: **%d of 12**." % (ZBAR, n_possig))
    A("- e8 t1.5 below the eta = 0 cell: **%d of 12**; at z <= -%.2f: **%d of 12**." % (n_neg, ZBAR, n_negsig))
