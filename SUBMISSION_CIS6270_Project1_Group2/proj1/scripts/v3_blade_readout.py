                tally[arm]["cont"].append(vc)
                tally[arm]["dec"].append(vd)
                tally[arm]["o2"].append(vo)
                A("| %s | %s | `%s` | %.4f / %.4f | %s | %+.2f | %s | %+.2f | %s | %+.2f | %d of 3 | %s | %s | %s / %s / %s |"
                  % (be, prop, arm, b["in_band_fraction"], pl["in_band_fraction"],
                     pp(d), z, pp(dd), zd, pp(ob - op), zo, pos,
                     pp(b["mol_stability"] - pl["mol_stability"]),
                     pp(b["validity"] - pl["validity"]), vc, vd, vo))
