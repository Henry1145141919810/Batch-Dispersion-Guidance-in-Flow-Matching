    A("")
    summ = []
    for be in ("fm", "equifm"):
        for prop in PROPS:
            for w in (1, 4):
                c = abl[(be, w)]
                base = P(c, prop, "bdg_e0t1")
                b0 = base["in_band_fraction"]
