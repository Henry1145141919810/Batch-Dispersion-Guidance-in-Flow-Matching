"""What the blade v3 run (n = 2000) says that its generated tables do not print,
and whether it agrees with the Betty v3 headline (n = 5000).

    python proj1/scripts/v3_blade_readout.py --md-out docs/results/V3_BLADE_READOUT.md

WHY THIS EXISTS. The blade run's README section (commit 23e8813) leads with
"BDG beats DPS by +0.95 pp in-band, paired, t = 5.71 over 18 pairs". No
generated table prints that number, so this script derives it from the cells,
prints the per-cell contrast beside it at the protocol's own bar, prints the
ablation grid the README's "tau reverses sign" claim rests on, and checks the
blade run against the Betty run that preceded it.

WHAT IT READS -- committed stats JSONs only, through v3_table's loader:
  results/v3/<be>/v3/n2000/seed*/      blade headline  (fm, equifm, edm)
  results/v3/<be>/v3abl/n2000/seed*/   blade ablation  (fm, equifm; w in {1,4})
  results/v3/<be>/n5000/seed*/         Betty headline  (flat tree; fm, equifm)

WHAT IT DOES NOT COMPUTE. Useful yield (decoded in-band AND stable, per
molecule) needs the *.permol.pt sidecars, which stay on blade. v3_paired.py
computes it there; see the doc this writes for the command.

STATISTICS. Contrasts are UNPAIRED, se = sqrt(p(1-p)/N) per arm with N = 3n,
as FULL_RUN_V3_PROTOCOL.md section 6.1 pre-registers, and verdicts are called at
its Bonferroni bar z = 2.99. Unpaired is conservative (arms share initial
noise), so a tie here can be a paired win; the paired reading is v3_paired.py's.
"""
