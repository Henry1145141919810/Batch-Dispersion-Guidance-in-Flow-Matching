    for be in ("fm", "equifm"):
        for prop in PROPS:
            pl = P(head[be], prop, "plug")
            plr = head[be][(prop, "plug")]
            for arm in BDG_HEAD:
                b = P(head[be], prop, arm)
                br = head[be][(prop, arm)]
                d = b["in_band_fraction"] - pl["in_band_fraction"]
                z = zdiff(b["in_band_fraction"], pl["in_band_fraction"], b["N"], pl["N"])
                dd = b["in_band_fraction_dec"] - pl["in_band_fraction_dec"]
                zd = zdiff(b["in_band_fraction_dec"], pl["in_band_fraction_dec"], b["N"], pl["N"])
                pos = sum(1 for x, y in zip(br, plr)
                          if x["in_band_fraction"] > y["in_band_fraction"])
                ob, op = o2(br), o2(plr)
                zo = zdiff(ob, op, b["N"], pl["N"])
