NL = chr(10)
PROPS = V.PROPS
SEEDS = ["20261001", "20261002", "20261003"]
ZBAR = 2.99                     # FULL_RUN_V3_PROTOCOL.md:582
BDG_HEAD = ("bdg_e4t0.5", "bdg_e4t1")
ETAS = (0, 1, 2, 4, 8)
TAUS = ("0.5", "0.75", "1", "1.5")


def arm_name(eta, tau):
    return "bdg_e0t1" if eta == 0 else "bdg_e%dt%s" % (eta, tau)


def load(root, be, n, stage, w=None, layout="staged"):
    cells, problems = V.load(root, be, n, SEEDS, stage=stage, w=w, layout=layout)
    if problems:
        sys.exit("refusing: %s/%s n%d: %s" % (be, stage, n, "; ".join(problems)))
    return cells


def se(p, N):
    return math.sqrt(max(p * (1 - p), 0.0) / N)


def zdiff(pa, pb, Na, Nb):
    s = math.sqrt(se(pa, Na) ** 2 + se(pb, Nb) ** 2)
    return (pa - pb) / s if s > 0 else float("nan")


def verdict(z):
    return "above" if z >= ZBAR else ("below" if z <= -ZBAR else "tie")


def pp(x):
    return "%+.2f" % (100 * x)


def mean(xs):
    return sum(xs) / len(xs)


def sd(xs):
    m = mean(xs)
    return math.sqrt(sum((x - m) ** 2 for x in xs) / (len(xs) - 1))


def o2(rows):
    """Second-oracle (OC-Flow, its own delta) in-band, pooled over seeds."""
    return sum(r["oracle2"]["in_band"] * r["n"] for r in rows) / sum(r["n"] for r in rows)


def w_eff(rows):
    """Measured deviation gain, mean over seeds (v3_table's pooled() reads seed 1 only)."""
    v = [(r.get("diag") or {}).get("bdg_w_eff") for r in rows]
    v = [x for x in v if x is not None]
    return mean(v) if v else None


def ranks(xs):
    order = sorted(range(len(xs)), key=lambda i: xs[i])
    r = [0.0] * len(xs)
    i = 0
    while i < len(order):
        j = i
        while j + 1 < len(order) and xs[order[j + 1]] == xs[order[i]]:
            j += 1
        for k in range(i, j + 1):
            r[order[k]] = (i + j) / 2.0 + 1
        i = j + 1
    return r


def spearman(a, b):
    ra, rb = ranks(a), ranks(b)
    ma, mb = mean(ra), mean(rb)
    num = sum((x - ma) * (y - mb) for x, y in zip(ra, rb))
    den = math.sqrt(sum((x - ma) ** 2 for x in ra) * sum((y - mb) ** 2 for y in rb))
    return num / den if den else float("nan")


