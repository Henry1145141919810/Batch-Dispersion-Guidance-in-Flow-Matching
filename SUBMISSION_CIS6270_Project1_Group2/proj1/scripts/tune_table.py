"""Tabulate the joint strength x start-time tune sweep. Read-only, CPU, seconds.

    python proj1/scripts/tune_table.py \
        --root results/tune/n1000 \
        --frozen <scratch>/frozen_tune.json \
        --logs "logs/tune-*.out" \
        --md-out docs/results/TUNE_N1000_RESULTS.md

WHAT IT IS FOR. `freeze_tune.py` picks the two operating points per (property,
arm) and prints the grid; it does not report the full metric block at each
pick, the head-to-heads, or the start-time effect. This script does, from the
same cells, using freeze_tune's OWN load/check/pick functions -- so the picks
here are the freeze's picks by construction, and `--frozen` cross-checks them
against a frozen_tune.json if one is given (it refuses on any disagreement).

WHAT IT REPORTS
  * provenance: cells read vs planned, n, seed, delta (and the v2
    pre-registered delta it replaces), generator, device, non-finite count,
    and -- with --logs -- the SLURM jobs that wrote the cells.
  * per (property, arm), the floor and open picks with the full metric block:
    in_band continuous and decoded, MAE / bias / residual sd over delta (each
    continuous with decoded in brackets), molecule stability, validity,
    uniqueness of valid, the number of candidate cells the pick was the
    maximum of, and grid-edge flags.
  * what the floor costs: open minus floor, in-band and chemistry.
  * each arm's floor pick against unguided and against plug's floor pick.
  * the start-time effect: best in-band at each t_min, a "when vs how"
    range comparison, and every arm at the fixed strength w = 1.
  * the full grid, as an appendix.

BIAS AND RESIDUAL SD come from the cell aggregates, not per-molecule sidecars
(the tune stage ran without --per-mol, so none exist): bias = f_B_mean -
target_mean, sd = sqrt(rmse^2 - bias^2). With a fixed target this is exact --
f_B_mean and prop_rmse_eval are both taken over the finite molecules
(evaluation.evaluate_samples) -- and it is the formula bdg_table.py and
bdg_full_metrics.py already use.

z-SCORES ARE UNPAIRED iid binomial: (p1 - p2) / sqrt(se1^2 + se2^2), se =
sqrt(p(1-p)/n). Every cell was sampled from the same seed (guidance_sweep
reseeds per cell), so two cells share initial noise and sizes; with no
sidecars the pairing cannot be used, and the unpaired se ignores that
correlation.

--md-out: if the file exists, it must hold both BEGIN/END marker pairs below
(main tables, appendix grid); only the text between each pair is replaced and
the hand-written prose around them is kept. If the file does not exist, the two
generated blocks are written as the whole file.
"""
