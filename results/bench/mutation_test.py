def run_test():
    """True only if EVERY gate file passes. A mutation is caught when any fails.

    Runs the SANDBOX copy's test files, which resolve their imports from their
    own location, so the working tree is never involved."""
    env = dict(os.environ, CUDA_VISIBLE_DEVICES="-1", PYTHONIOENCODING="utf-8")
    for t in TEST_REL:
        r = subprocess.run([PY, _p(t)], capture_output=True, text=True,
                           env=env, timeout=900)
        if r.returncode != 0 or "ALL PASS" not in r.stdout:
            return False
    return True


def main():
    global SANDBOX
    SANDBOX = tempfile.mkdtemp(prefix="mutation_sandbox_")
    for sub in ("src", "scripts", "tests"):
        shutil.copytree(os.path.abspath(os.path.join("proj1", sub)),
                        os.path.join(SANDBOX, "proj1", sub),
                        ignore=shutil.ignore_patterns("__pycache__"))
    print("sandbox: %s" % SANDBOX)
    print("the working tree is never written to by this script\n")

    files = sorted({m[3] if len(m) > 3 else SRC for m in MUTATIONS})
    original = {f: io.open(_p(f), encoding="utf-8").read() for f in files}
    caught = survived = 0
    try:
        if not run_test():
            print("BASELINE FAILS -- fix the gates before mutating")
            return 1
        print("baseline: ALL PASS\n")
        print("%-52s %s" % ("injected defect", "caught?"))
        print("-" * 64)
        for mut in MUTATIONS:
            name, old, new = mut[0], mut[1], mut[2]
            tgt = mut[3] if len(mut) > 3 else SRC
            src = original[tgt]
            if old not in src:
                print("%-52s %s" % (name, "ANCHOR MISSING"))
                survived += 1
                continue
            io.open(_p(tgt), "w", encoding="utf-8", newline="\n").write(
                src.replace(old, new, 1))
            ok = run_test()
            if ok:
                print("%-52s %s" % (name, "NO  <-- gate does not constrain this"))
                survived += 1
            else:
                print("%-52s %s" % (name, "yes"))
                caught += 1
            io.open(_p(tgt), "w", encoding="utf-8", newline="\n").write(src)
    finally:
        shutil.rmtree(SANDBOX, ignore_errors=True)
    print("-" * 64)
    print("caught %d / %d" % (caught, caught + survived))
    print("gates are sound" if survived == 0 else "SOME DEFECTS SURVIVE")
    return 0 if survived == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
